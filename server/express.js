import express from 'express';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import userRoutes from './routes/user.routes.js';
import authRoutes from './routes/auth.routes.js';
import contactRoutes from './routes/contact.routes.js';
import projectRoutes from './routes/project.routes.js';
import qualificationRoutes from './routes/qualification.routes.js';
const app = express();
app.use(helmet());
app.use(express.json());
app.use(cookieParser());
app.use(userRoutes, authRoutes);
app.use('/api/contacts', contactRoutes);
app.use('/api/projects', projectRoutes);
app.use('/api/qualifications', qualificationRoutes);
app.get('/', (req,res)=>res.json({message:'Portfolio API'}));
app.use((err,req,res,next)=>res.status(err.name==='UnauthorizedError'?401:500).json({error:err.name==='UnauthorizedError'?'Please sign in again':'Server error'}));
export default app;
